import assert from 'node:assert/strict';
import {createPose,step} from '../../dist/rov-simulator/physics.mjs';
const zero={forward:0,strafe:0,yaw:0,vertical:0,pitch:0,roll:0};
let p=createPose();for(let i=0;i<100;i++)step(p,{...zero,vertical:1},.02,false);assert(p.depth<1.2,'R ascends');
p=createPose();for(let i=0;i<100;i++)step(p,{...zero,vertical:-1},.02,false);assert(p.depth>1.2,'negative heave descends');
p=createPose();for(let i=0;i<100;i++)step(p,{...zero,forward:1},.02,false);assert(p.z<0,'W forward');assert.equal(p.x,0);
p=createPose();for(let i=0;i<10000;i++)step(p,{...zero,forward:1,strafe:1,vertical:-1},.02,false);assert(p.x<=2.55&&p.z>=-5.55&&p.depth<=2.7);assert(p.boundary);
p=createPose();for(let i=0;i<100;i++)step(p,{...zero,vertical:-1},.02,false,true);assert.equal(p.depth,1.2,'depth hold');
p=createPose();for(let i=0;i<100;i++)step(p,{...zero,yaw:1},.02,false);assert(p.yaw>0,'positive yaw turns');
p=createPose();for(let i=0;i<100;i++)step(p,{...zero,pitch:1,roll:-1},.02,false);assert(p.pitch<=35&&p.roll>=-35);
console.log('PASS: ascend, descend, forward, tank limits, depth hold, yaw and attitude bounds');
